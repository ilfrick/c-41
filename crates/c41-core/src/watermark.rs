    #[test]
    fn centred_default_composites_deterministically() {
        // A 40×30 grey frame, watermark at the defaults (centred, 100 %
        // opacity, no rotation): the emblem's ring lands over the frame and
        // whitenens the covered pixels; two runs must agree bit-for-bit.
        let (w, h) = (40usize, 30usize);
        let input = vec![0.25f32; w * h * 4]; // alpha lane 1.0 included
        let mut a = vec![0.0f32; w * h * 4];
        let mut b = vec![0.0f32; w * h * 4];
        let p = WatermarkParams::default();
        Watermark::apply(&input, &mut a, w, h, &p, 1.0);
        Watermark::apply(&input, &mut b, w, h, &p, 1.0);
        assert_eq!(a, b, "the composite must be deterministic");
        assert_ne!(a, input, "a centred opaque watermark changes the frame");
        // Maximum luminance must reach ~the asset's white (blend at full
        // opacity, alpha 1 → out = (1-1)*in + 1*(1.0) = 1.0 in linear
        // display light, subject to the bilinear edge); at least some pixels
        // must be near the asset's white value.
        assert!(
            a.as_chunks::<4>().0.iter().any(|px| px[0] > 0.98 && px[1] > 0.98 && px[2] > 0.98),
            "the white emblem must land somewhere near full brightness"
        );
        // Alpha lane 3 is the input's — the kernel passes channel 4 through
        // (wm alpha never bleeds into the frame alpha).
        assert!(a.as_chunks::<4>().0.iter().all(|px| px[3] == 0.25), "frame alpha is untouched");
    }

    #[test]
    fn scale_one_paints_crisp_texels() {
        // The paint must evaluate destination pixel CENTRES (x+0.5, y+0.5)
        // through the inverse transform — pixman's convention. At marker
        // scale 1.0 (a 160×160 frame sized to the builtin emblem) every
        // destination pixel then maps onto an exact source texel, so:
        //   - texel (145, 80) — inside the ring (dist 65 of 54..66) — fills
        //     the blend to pure white (alpha 1, no interpolation), and
        //   - texel (147, 80) — outside the ring (dist 67) — stays EXACTLY
        //     the background (alpha 0, no bleed from the 50 %-coverage edge
        //     texel 146 in between).
        // A half-pixel phase error (integer-index sampling, the pre-review
        // bug) blurs both: it averages texel pairs (146,147) / (144,145),
        // turning the (147, 80) probe grey. This test is the regression pin.
        let (w, h) = (160usize, 160usize);
        let input = vec![0.25f32; w * h * 4];
        let mut out = vec![0.0f32; w * h * 4];
        Watermark::apply(&input, &mut out, w, h, &WatermarkParams::default(), 1.0);
        let outside = (80 * w + 147) * 4;
        assert_eq!(
            out[outside], 0.25,
            "a transparent texel must composite exactly the background"
        );
        let inside = (80 * w + 145) * 4;
        assert_eq!(
            out[inside], 1.0,
            "a solid-white texel must composite without interpolation to 1.0"
        );
        assert!(out.iter().all(|v| v.is_finite()));
    }

