    #[test]
    fn tiny_and_degenerate_frames_do_not_panic() {
        // A 1×1 frame: the emblem is way larger than the frame — the sample
        // footprint is almost always outside the source bitmap, and anything
        // in the middle still blends safely (the C handles this by painting
        // the oversized surface and blending the whole ROI).
        let input = vec![0.5f32; 4];
        let mut out = vec![0.0f32; 4];
        Watermark::apply(&input, &mut out, 1, 1, &WatermarkParams::default(), 1.0);
        assert!(out.iter().all(|v| v.is_finite()));

        // 0×0 must be a no-op, and a NaN blob must not poison the maths.
        let empty: Vec<f32> = vec![];
        let mut oe = vec![];
        Watermark::apply(&empty, &mut oe, 0, 0, &WatermarkParams::default(), 1.0);
        assert!(oe.is_empty());
        let mut out2 = vec![0.0f32; 4];
        let p = WatermarkParams {
            opacity: f32::NAN,
            scale: f32::NAN,
            rotate: f32::NAN,
            xoffset: f32::NAN,
            yoffset: f32::NAN,
            ..WatermarkParams::default()
        };
        // NaN folds to the C `reload_defaults` values (opacity 100, scale 100,
        // rotate 0 — the same convention as the S2 `cac_strength` fold, NOT a
        // neutral 0): a corrupt blob renders the default watermark rather than
        // poisoning the maths. Pin the fold by equating with an explicit
        // default-params run on the same fully-covered 1×1 frame.
        Watermark::apply(&input, &mut out2, 1, 1, &p, 1.0);
        let mut dft = vec![0.0f32; 4];
        Watermark::apply(&input, &mut dft, 1, 1, &WatermarkParams::default(), 1.0);
        assert_eq!(out2, dft, "NaN params must fold to the C defaults");
        assert!(out2.iter().all(|v| v.is_finite()));
    }

    #[test]
    fn rotation_swaps_the_bounding_axis() {
        // At 90°, bb_w and bb_h swap: the layout boxes for a wide marker get
        // their height swapped. Exercise the rotation path end-to-end and
        // verify it is deterministic and finite — exact pixel parity with
        // Cairo's rotate filter is not claimed at 45°, but axis-swap geometry
        // is exercised by the 4:3-frame composite differing from the no-rotate
        // one.
        let (w, h) = (32usize, 32usize);
        let input = vec![0.3f32; w * h * 4];
        let mut no_rot = vec![0.0f32; w * h * 4];
        let mut rot = vec![0.0f32; w * h * 4];
        Watermark::apply(&input, &mut no_rot, w, h, &WatermarkParams::default(), 1.0);
        Watermark::apply(
            &input,
            &mut rot,
            w,
            h,
            &WatermarkParams { rotate: 90.0, ..WatermarkParams::default() },
            1.0,
        );
        assert_ne!(no_rot, rot, "rotation must change the composite");
        assert!(rot.iter().all(|v| v.is_finite()));
    }
